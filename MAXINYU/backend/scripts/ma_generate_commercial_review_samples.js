function ma_createWorkbook(ma_rows) {
  const ma_sheet = ma_xlsx.utils.aoa_to_sheet([ma_headers, ...ma_rows]);
  ma_sheet["!cols"] = [
    { wch: 12 },
    { wch: 24 },
    { wch: 78 },
    { wch: 10 },
    { wch: 18 }
  ];
  const ma_workbook = ma_xlsx.utils.book_new();
  ma_xlsx.utils.book_append_sheet(ma_workbook, ma_sheet, "商业评论");
  return ma_workbook;
}

for (const ma_dataset of ma_datasets) {
  const ma_rows = ma_dataset.ma_comments.map((ma_comment, ma_index) => [
    `R${String(ma_index + 1).padStart(3, "0")}`,
    ma_dataset.ma_product,
    ma_comment[2],
    ma_comment[1],
    `2026-11-${String(16 - ma_index % 12).padStart(2, "0")}`
  ]);
  ma_xlsx.writeFile(ma_createWorkbook(ma_rows), ma_path.join(ma_projectRoot, ma_dataset.ma_fileName));
}

ma_xlsx.writeFile(
  ma_createWorkbook([]),
  ma_path.join(ma_projectRoot, "ma_commercial_reviews_template.xlsx")
);
